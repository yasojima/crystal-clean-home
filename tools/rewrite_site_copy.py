def paraphrase(data: str) -> tuple[str, int]:
    repaired = data
    repair_count = 0
    for old, new in REPAIRS:
        hits = repaired.count(old)
        if hits:
            repaired = repaired.replace(old, new)
            repair_count += hits
    if repair_count:
        return repaired, repair_count
    if "\n" in data.strip() or "\r" in data.strip():
        exact_ok = False
    else:
        exact_ok = True
    plain = data.strip()
    bullet = "・" if plain.startswith("・") else ""
    sentence = plain[len(bullet):]
    if sentence in TARGET_SENTENCES:
        return data, 0
    if exact_ok and sentence in SENTENCES:
        start = len(data) - len(data.lstrip())
        end = len(data.rstrip())
        replacement = bullet + SENTENCES[sentence]
        return data[:start] + replacement + data[end:], 1
    if exact_ok and re.search(r"で\d{4}/\d{1,2}/\d{1,2}に放送されました[。]?$", plain):
        replacement = re.sub(r"で(\d{4}/\d{1,2}/\d{1,2})に放送されました", r"の\1放送回で紹介されました", plain)
        start = len(data) - len(data.lstrip())
        end = len(data.rstrip())
        return data[:start] + replacement + data[end:], 1
    if "公開記念コラボ企画" in plain and "クリスタルクリーンホーム×" in plain:
        updated = data.replace("クリスタルクリーンホーム×", "クリスタルクリーンホームと")
        updated = updated.replace("公開記念コラボ企画", "公開を記念した共同企画")
        return updated, 1
    if len(plain) < 18 or not any(c in plain for c in "。、！？?!"):
        return data, 0
    updated = data
    count = 0
    for old, new in PHRASES:
        hits = updated.count(old)
        if hits:
            updated = updated.replace(old, new)
            count += hits
    if not count:
        return data, 0
    # A large expansion in a fixed-size card is less useful than the old copy.
    if len(updated) > len(data) * 1.24 or len(updated) < len(data) * .76:
        return data, 0
    return updated, count


