def replace_group(text: str, pattern: str, values: list[str], label: str) -> str:
    matches = list(re.finditer(pattern, text, re.DOTALL))
    if len(matches) != len(values):
        raise ValueError(f"{label}: expected {len(values)} cards, found {len(matches)}")
    iterator = iter(values)
    return re.sub(pattern, lambda m: m.group(1) + next(iterator) + m.group(3), text, flags=re.DOTALL)


